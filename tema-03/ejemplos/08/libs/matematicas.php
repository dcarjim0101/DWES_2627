<?php

/*
    declaración de funciones matemáticas:
    -sumar: recibe dos numeros enteros y devuelve su suma
    -restar: recibe dos numeros enteros y devuelve su resta
    -multiplicar: recibe dos numeros enteros y devuelve su multiplicación
*/

function sumar(int $a, int $b) {
    return $a + $b;
}

function restar(int $a, int $b) {
    return $a - $b;
}

function multiplicar(int $a, int $b) {
    return $a * $b;
}